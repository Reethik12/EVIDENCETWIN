const CUSTOM_KITS_STORAGE_KEY = 'evidencetwin_custom_kit_profiles_v1';

export function getAllKitProfiles(): TestKitProfile[] {
  try {
    const customJson = localStorage.getItem(CUSTOM_KITS_STORAGE_KEY);
    if (customJson) {
      const customKits: TestKitProfile[] = JSON.parse(customJson);
      return [...DEMO_KIT_PROFILES, ...customKits];
    }
  } catch (e) {
    console.warn('Could not load custom kit profiles from localStorage', e);
  }
  return DEMO_KIT_PROFILES;
}

export function saveCustomKitProfile(profile: TestKitProfile): void {
  try {
    const existing = getAllKitProfiles().filter(
      (k) => !DEMO_KIT_PROFILES.some((d) => d.id === k.id)
    );
    const updated = [...existing.filter((k) => k.id !== profile.id), profile];
    localStorage.setItem(CUSTOM_KITS_STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.warn('Could not save custom kit profile to localStorage', e);
  }
}
